-- ------------------------------------------------------------
-- 2. CREATE FRESH PRODUCTION TABLES
-- ------------------------------------------------------------

-- A. USERS (Admin, Manager, Agent, and Customer Accounts)
create table public.users (
  id text primary key,
  email text unique not null,
  full_name text not null,
  role text not null default 'customer', -- 'admin', 'manager', 'agent', 'customer'
  active boolean not null default true,
  activated boolean not null default true,
  activation_code text, -- stores temporary OTP or hashed "PW:<password>"
  reset_code text,
  avatar_url text,
  intro text,
  created_at timestamptz not null default now()
);

-- B. LOGIN HISTORY (Audit trail for logins and logouts)
create table public.login_history (
  id bigserial primary key,
  user_id text,
  email text,
  role text,
  action text not null default 'login',
  created_at timestamptz not null default now()
);

-- C. AGENT LINKS (Referral links generated by Agents)
create table public.agent_links (
  id bigserial primary key,
  agent_id text,
  agent_email text,
  agent_name text,
  link_code text unique not null,
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- D. PLANS (Red Fiber Internet Service Plans)
create table public.plans (
  id text primary key,
  name text not null,
  speed integer not null,
  price numeric not null,
  tag text,
  featured boolean not null default false,
  active boolean not null default true
);

-- E. WEBSITE CONTENT (CMS Data: Banners, About, FAQs, Area Strips)
create table public.website_content (
  id text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- F. SYSTEM SETTINGS (Global switches: AI on/off, Maintenance Mode)
create table public.system_settings (
  id text primary key,
  ai_enabled boolean not null default true,
  maintenance_mode boolean not null default false,
  maintenance_message text default '',
  updated_at timestamptz not null default now()
);

-- G. APPLICATIONS (Customer Registration, Geolocation & Fiber Submissions)
create table public.applications (
  id uuid primary key default gen_random_uuid(),
  ref_no text unique not null,
  reference_no text,
  customer_id text,
  agent_id text,
  agent_link_code text,
  assigned_agent text,
  plan text,
  plan_id text,
  plan_name text,
  first_name text,
  middle_name text default 'N/A',
  last_name text,
  full_name text not null,
  birth_date text,
  phone text not null,
  phone_alt text,
  email text not null,
  house_no text,
  house_suffix text,
  unit_no text,
  unit_type text default 'Residential',
  floor_no text,
  building_name text default 'N/A',
  street text,
  subdivision text default 'N/A',
  barangay text,
  city text,
  province text,
  landmark text,
  address_line text,
  lat double precision default 14.3294,
  lng double precision default 120.9367,
  latitude double precision,
  longitude double precision,
  id_type text not null,
  id_number text not null,
  id_front_path text,
  id_back_path text,
  id_image_url text,
  remarks text,
  agree_tu boolean default false,
  original_copy jsonb,
  original_submission jsonb,
  corrected_copy jsonb,
  has_correction boolean default false,
  screening jsonb default '{}'::jsonb,
  ai_result jsonb,
  ai_log jsonb default '[]'::jsonb,
  status text not null default 'Pending Review', -- 'Pending Review', 'Under Agent Review', 'Needs Correction', 'Approved', 'Rejected'
  correction_note text,
  agent_remarks text,
  provider_ref text,
  provider_remarks text,
  customer_instruction text,
  encoded boolean default false,
  encoded_proof text,
  encoding_proof_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- H. DOCUMENTS (Identification uploads linked to applications)
create table public.documents (
  id bigserial primary key,
  application_id uuid,
  doc_type text not null,
  file_path text not null,
  version text not null default 'original',
  created_at timestamptz not null default now()
);

-- I. SCREENINGS (OpenCV, PaddleOCR & Ollama preliminary logs)
create table public.screenings (
  id bigserial primary key,
  application_id uuid,
  quality jsonb,
  ocr jsonb,
  comparisons jsonb,
  ai_remark text,
  status text not null default 'completed',
  created_at timestamptz not null default now()
);

-- J. CORRECTIONS (Agent requests & Customer update audit)
create table public.corrections (
  id bigserial primary key,
  application_id uuid,
  agent_id text,
  issue_note text not null,
  customer_response jsonb,
  status text not null default 'Pending Customer',
  created_at timestamptz not null default now()
);

-- K. NOTIFICATIONS (User alerts with clickable URLs)
create table public.notifications (
  id bigserial primary key,
  user_id text,
  email text,
  role text,
  title text not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

-- L. SYSTEM LOGS (Admin audit trail for technical operations)
create table public.system_logs (
  id bigserial primary key,
  actor_email text,
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);

